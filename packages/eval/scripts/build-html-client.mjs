import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const pkg = fileURLToPath(new URL("../", import.meta.url));
const client = `${pkg}client/`;
const target = `${pkg}src/reporters/html/client.generated.ts`;

async function bundle(entry, options) {
  const output = await build({
    absWorkingDir: client,
    entryPoints: [entry],
    bundle: true,
    write: false,
    minify: true,
    legalComments: "none",
    charset: "utf8",
    logLevel: "silent",
    ...options,
  });
  const [file] = output.outputFiles;
  if (file === undefined) throw new Error(`esbuild produced no output for ${entry}`);
  return file.text.trim();
}

const script = await bundle("main.ts", { format: "iife", platform: "browser", target: "es2022" });
const style = await bundle("report.css", { loader: { ".css": "css" } });

const forbidden = [
  [script, /\binnerHTML\b|\bouterHTML\b|insertAdjacentHTML|document\.write/, "the client must build the page from text nodes, not parsed markup"],
  [script, /https?:\/\//, "the report must not reference the network"],
  [script, /\bimport\s*\(|^import\s/m, "the client must be one self-contained script"],
  [script, /<\/script|<!--|<script/i, "the client must not be able to end or nest its <script> element"],
  [script, /sourceMappingURL/, "the client must not reference a source map"],
  [style, /<\/style/i, "the styles must not be able to end their <style> element"],
  [style, /url\(|@import/i, "the styles must not load anything"],
];
for (const [text, pattern, why] of forbidden) {
  if (pattern.test(text)) throw new Error(`HTML client bundle rejected (${why}): ${pattern}`);
}

const generated = [
  "// Generated by packages/eval/scripts/build-html-client.mjs from packages/eval/client. Do not edit.",
  "",
  "/** The bundled HTML report client. */",
  `export const CLIENT_SCRIPT = ${JSON.stringify(script)};`,
  "",
  "/** The HTML report styles. */",
  `export const CLIENT_STYLE = ${JSON.stringify(style)};`,
  "",
].join("\n");

if (process.argv.includes("--check")) {
  const current = await readFile(target, "utf8").catch(() => "");
  if (current !== generated) {
    console.error(`${target} is stale. Run: node packages/eval/scripts/build-html-client.mjs`);
    process.exit(1);
  }
} else {
  await writeFile(target, generated);
  console.log(`Wrote ${target} (script ${(script.length / 1024).toFixed(1)} KiB, styles ${(style.length / 1024).toFixed(1)} KiB).`);
}
